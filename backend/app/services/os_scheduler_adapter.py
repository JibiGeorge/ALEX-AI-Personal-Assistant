"""
OS Native Scheduled Reminders Adapter (GAP-10).

Provides persistent operating system level reminder scheduling across:
- Windows: Windows Task Scheduler (schtasks.exe with XML definition)
- macOS: launchd LaunchAgents (~/Library/LaunchAgents/*.plist with launchctl)
- Linux: systemd-run --user timers or 'at' daemon

Fires desktop notifications and audio cues even when the Alex application process is completely closed.
"""

from __future__ import annotations

from datetime import datetime, timezone
import json
import logging
import os
