import platform
import shutil
import subprocess
import sys
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

_CNW: Dict[str, Any] = (
    {"creationflags": subprocess.CREATE_NO_WINDOW}
    if platform.system() == "Windows"
    else {}
)


def get_current_os() -> str:
    """Return normalized OS identifier: 'mac', 'windows', or 'linux'."""
    sys_name = platform.system()
    if sys_name == "Darwin":
        return "mac"
    if sys_name == "Windows":
        return "windows"
    return "linux"


def sanitise_message(text: str, max_len: int = 200) -> str:
    """Sanitize notification text against shell escaping and formatting bugs."""
    clean = (
        text.replace("\\", "")
        .replace('"', "")
        .replace("'", "")
        .replace("\n", " ")
        .replace("\r", "")
        .strip()
    )
    return clean[:max_len]


class OSSchedulerAdapter:
    """Adapter for interacting with host OS background schedulers."""

    def __init__(
        self,
        scripts_dir: Optional[Path] = None,
        agents_dir: Optional[Path] = None,
        enabled: bool = True,
    ) -> None:
        self._scripts_dir = scripts_dir or (Path.home() / ".alex" / "reminders")
        self._agents_dir = agents_dir or (Path.home() / "Library" / "LaunchAgents")
        self._enabled = enabled

    @property
    def enabled(self) -> bool:
        return self._enabled

    @enabled.setter
    def enabled(self, value: bool) -> None:
        self._enabled = value

    @property
    def scripts_dir(self) -> Path:
        self._scripts_dir.mkdir(parents=True, exist_ok=True)
        return self._scripts_dir

    @property
    def agents_dir(self) -> Path:
        self._agents_dir.mkdir(parents=True, exist_ok=True)
        return self._agents_dir

